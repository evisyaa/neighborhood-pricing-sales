-- Neighborhood Pricing Sales App — Supabase schema
-- Run in Supabase SQL Editor once.

create table if not exists public.sales_users (
  auth_uid uuid primary key references auth.users(id) on delete cascade,
  sales_code text unique not null,
  sales_name text not null,
  depo text,
  region text,
  role text not null default 'salesman' check (role in ('salesman','manager')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.engine_grosir_result (
  id bigint generated by default as identity primary key,
  sales_code text not null,
  sales_name text,
  outlet_code text not null,
  outlet_name text not null,
  region text,
  depo text,
  segment text,
  lat double precision not null,
  lon double precision not null,
  roa_3m boolean not null default false,
  roa_jun boolean not null default false,
  roa_jul boolean not null default false,
  roa_aug boolean not null default false,
  omzet_jun numeric default 0,
  omzet_jul numeric default 0,
  omzet_aug numeric default 0,
  ec_jun numeric default 0,
  ec_jul numeric default 0,
  ec_aug numeric default 0,
  radius text not null check (radius in ('P25','P50','P75')),
  quadrant_code integer not null,
  quadrant text not null,
  action text,
  retail_roa_pct numeric,
  retail_base integer default 0,
  benchmark numeric,
  opportunity_score numeric,
  confidence text,
  profile text,
  radius_km numeric,
  current_month numeric default 0,
  target_month numeric default 0,
  gross_gap numeric default 0,
  potential_month numeric default 0,
  ec_avg numeric,
  recommended_order numeric default 0,
  strata text,
  updated_at timestamptz not null default now(),
  unique(outlet_code, radius)
);

create table if not exists public.sales_retail_points (
  id bigint generated by default as identity primary key,
  sales_code text not null,
  sales_name text,
  outlet_code text unique not null,
  outlet_name text not null,
  region text,
  depo text,
  lat double precision not null,
  lon double precision not null,
  roa_3m boolean not null default false,
  updated_at timestamptz not null default now()
);

create table if not exists public.usage_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  auth_uid uuid not null default auth.uid(),
  sales_code text not null,
  outlet_code text,
  event_type text not null,
  radius text,
  recommended_order numeric default 0,
  actual_order numeric default 0,
  lat double precision,
  lon double precision,
  extra jsonb
);

create index if not exists idx_engine_sales_radius on public.engine_grosir_result(sales_code, radius);
create index if not exists idx_engine_lat_lon on public.engine_grosir_result(lat, lon);
create index if not exists idx_retail_sales on public.sales_retail_points(sales_code);
create index if not exists idx_usage_sales_created on public.usage_events(sales_code, created_at desc);

-- Helper functions execute as table owner so policies can safely read sales_users.
create or replace function public.current_sales_code()
returns text language sql stable security definer set search_path=public as $$
  select sales_code from public.sales_users where auth_uid = auth.uid() and active = true limit 1;
$$;

create or replace function public.current_app_role()
returns text language sql stable security definer set search_path=public as $$
  select role from public.sales_users where auth_uid = auth.uid() and active = true limit 1;
$$;

grant execute on function public.current_sales_code() to authenticated;
grant execute on function public.current_app_role() to authenticated;

alter table public.sales_users enable row level security;
alter table public.engine_grosir_result enable row level security;
alter table public.sales_retail_points enable row level security;
alter table public.usage_events enable row level security;

-- Re-running this file: remove policies first if they exist.
drop policy if exists "profile own or manager" on public.sales_users;
drop policy if exists "engine own coverage or manager" on public.engine_grosir_result;
drop policy if exists "retail own coverage or manager" on public.sales_retail_points;
drop policy if exists "usage insert own" on public.usage_events;
drop policy if exists "usage read own or manager" on public.usage_events;

create policy "profile own or manager" on public.sales_users
for select to authenticated
using (auth_uid = auth.uid() or public.current_app_role() = 'manager');

create policy "engine own coverage or manager" on public.engine_grosir_result
for select to authenticated
using (sales_code = public.current_sales_code() or public.current_app_role() = 'manager');

create policy "retail own coverage or manager" on public.sales_retail_points
for select to authenticated
using (sales_code = public.current_sales_code() or public.current_app_role() = 'manager');

create policy "usage insert own" on public.usage_events
for insert to authenticated
with check (auth_uid = auth.uid() and sales_code = public.current_sales_code());

create policy "usage read own or manager" on public.usage_events
for select to authenticated
using (auth_uid = auth.uid() or public.current_app_role() = 'manager');
